export const LIBRARY = BOOKS.map((b) => {
  const e = EXTRA[b.id];
  const chapters = e.contents.reduce((n, p) => n + p.items.length, 0);
  const words = CHAPTERS[b.id].reduce((n, c) => n + c.words, 0);
  return { ...b, ...e, words, chapters, parts: CHAPTERS[b.id], hours: Math.round(words / 180 / 60) };
});

export const getBook = (id) => LIBRARY.find((b) => b.id === id);

// Стан читалки (позиція, прогрес, цитати, закладки, словничок) зберігається у браузері.
const EMPTY = { progress: 0, pos: null, read: {}, quotes: [], bookmarks: [], words: [] };

export function readerState(id) {
  try {
    return { ...EMPTY, ...JSON.parse(localStorage.getItem(`reader:${id}`) || "{}") };
  } catch {
    return { ...EMPTY };
  }
}

export function saveReaderState(id, state) {
  try {
    localStorage.setItem(`reader:${id}`, JSON.stringify(state));
  } catch {
    /* без збереження: приватний режим або переповнене сховище */
  }
}

// Розділи вантажаться по одному й кешуються на час сесії.
const cache = new Map();
export function loadChapter(id, n) {
  const key = `${id}/${n}`;
  if (!cache.has(key)) {
    // ?v= змінюється з кожною збіркою, щоб браузер не показував старий текст після оновлення
    const url = `./books/${id}/${String(n).padStart(2, "0")}.json?v=${__BUILD_ID__}`;
    cache.set(
      key,
      fetch(url).then((r) => {
        if (!r.ok) throw new Error(`Не вдалося завантажити розділ (${r.status})`);
        return r.json();
      }).catch((e) => {
        cache.delete(key);
        throw e;
      })
    );
  }
  return cache.get(key);
}
